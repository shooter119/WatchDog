// Keep App display names aligned with the canonical web/backend standard.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const source = JSON.parse(readFileSync(new URL('../backend/admin/key-site-schema.json', import.meta.url)));
const dart = value => JSON.stringify(value);
const output = '// Generated by scripts/generate-key-site-schema.mjs; edit the canonical JSON.\n'
  + 'const keySiteFieldLabels = <String, String>{\n'
  + Object.entries(source.fieldLabels).map(([key, value]) => `  ${dart(key)}: ${dart(value)},`).join('\n')
  + '\n};\nconst keySiteRecordLabels = <String, String>{\n'
  + Object.entries(source.kinds).map(([key, spec]) => `  ${dart(key)}: ${dart(spec.label)},`).join('\n') + '\n};\n';
const path = fileURLToPath(new URL('../app/lib/models/key_site_schema.dart', import.meta.url));
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('App standard labels are stale; run node scripts/generate-key-site-schema.mjs');
} else writeFileSync(path, output);
